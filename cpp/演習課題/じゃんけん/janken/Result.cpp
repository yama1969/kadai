/******************************************************************************
 * クラスResult
 * 　勝負分を記録するクラス
 ******************************************************************************/
#include "Result.h"

/******************************************************************************
 * コンストラクタ
 * 　各種初期化
 * 引数：なし
 ******************************************************************************/
Result::Result(){
	win_num = 0;
	lose_num = 0;
	draw_num = 0;
}

/******************************************************************************
 * 関数win()
 * 　勝ち数を１加算する
 * 引数：なし
 * 戻値：int 勝ち数の加算結果
 ******************************************************************************/
int Result::win(){
	return ++win_num;
}

/******************************************************************************
 * 関数lose()
 * 　負け数を１加算する
 * 引数：なし
 * 戻値：int 負け数の加算結果
 ******************************************************************************/
int Result::lose(){
	return ++lose_num;
}

/******************************************************************************
 * 関数draw()
 * 　引分け数を１加算する
 * 引数：なし
 * 戻値：int 引分けの加算結果
 ******************************************************************************/
int Result::draw(){
	return ++draw_num;
}

/******************************************************************************
 * 関数getWin()
 * 　現在の勝ち数を得る
 * 引数：なし
 * 戻値：int 現在の勝ち数
 ******************************************************************************/
int Result::getWin(){
	return win_num;
}

/******************************************************************************
 * 関数getLose()
 * 　現在の負け数を得る
 * 引数：なし
 * 戻値：int 現在の負け数
 ******************************************************************************/
int Result::getLose(){
	return lose_num;
}

/******************************************************************************
 * 関数getDraw()
 * 　現在の引分け数を得る
 * 引数：なし
 * 戻値：int 現在の引分け数
 ******************************************************************************/
int Result::getDraw(){
	return draw_num;
}
