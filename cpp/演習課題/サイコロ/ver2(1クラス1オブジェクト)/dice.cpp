#include <iostream>
#include <ctime>
using namespace std;

/**************************************************************************
 * クラスDice：サイコロクラス
 **************************************************************************/
#include "dice.h"

//-------------------------------------------------------------------------
//Diceコンストラクタ
//引数：int max : 目の最大値
//-------------------------------------------------------------------------
Dice::Dice(int max){
	srand((unsigned)time(NULL));
	if(max < 1){
		max = 6;
	}
	this->max = max;
	throwDice();
}

//-------------------------------------------------------------------------
//関数throwDice() : サイコロを投げる
//引数：なし
//戻値：int 出た目
//-------------------------------------------------------------------------
int Dice::throwDice(){
	num = rand() % max + 1;
	return num;
}

//-------------------------------------------------------------------------
//関数getNum() : サイコロの目を得る
//引数：なし
//戻値：int サイコロの目
//-------------------------------------------------------------------------
int Dice::getNum(){
	return num;
}

//-------------------------------------------------------------------------
//関数compNum() : サイコロの目を比較する
//引数：int n : 比較する数
//戻値：int 結果(-1:目は小さい,0:等しい,1:目は大きい)
//-------------------------------------------------------------------------
int Dice::compNum(int n){
	if(num < n){
		return -1;
	}else if(num > n){
		return 1;
	}
	return 0;
}
