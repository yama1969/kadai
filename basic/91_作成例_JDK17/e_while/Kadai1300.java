package e_while;

/******************************************************************************
 * 数字を表示(1～10降順)
 *****************************************************************************/
public class Kadai1300{
    public static void main(String[] args){
        int i = 10;                 //初期値 = 10
        while(i > 0){               //1ずつ減じながら1まで繰り返す
            System.out.println(i);
            i--;
        }
    }
}
