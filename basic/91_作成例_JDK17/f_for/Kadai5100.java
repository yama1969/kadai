package f_for;
/******************************************************************************
 * 0.1を繰り返し加算する(丸め誤差の実験)
 *****************************************************************************/
public class Kadai5100{
    public static void main(String[] args){
        //加算用変数を準備
        double d = 0.0;
        
        //0.1を百万回加算する
        for(int i = 0; i < 1000000; i++){
            d += 0.1;
        }
        
        //結果表示
        System.out.println(d);
    }
}
