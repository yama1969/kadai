/******************************************************************************
 * int型の＋側オーバーフローを実験する
 *****************************************************************************/
public class Kadai1700{
    public static void main(String[] args){
        int a = 2147483647;                  //int型の最大値を代入
        System.out.println("a     = " + a);  //表示
        a += 1;                              //最大値にさらに1を加算
        System.out.println("a + 1 = " + a);  //どのような値になるか？
    }
}
