/******************************************************************************
 * 文字を繰り返し表示
 *****************************************************************************/
public class Kadai1800{
    public static void main(String[] args){
        //1行の表示を20回繰り返す
        for(int i = 1; i < 21; i++){
            //1行の表示(*の表示をi回繰り返す)
            for(int j = 0; j < i; j++){
                System.out.print('*');  //*の表示
            }
            System.out.println();       //改行
        }
    }
}
