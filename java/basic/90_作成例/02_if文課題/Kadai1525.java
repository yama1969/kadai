/******************************************************************************
 * 駅まで何で行きますか
 *****************************************************************************/
public class Kadai1525{
    public static void main(String[] args){
        //駅までの距離の入力
        int dist = Keyboard.readInt("駅までの距離[km]");
        
        //距離から判断した結果を表示
        if(dist > 3){
            System.out.println("タクシーで行きます。");
        }else{
            System.out.println("徒歩で行きます。");
        }
    }
}
