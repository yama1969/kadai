/******************************************************************************
 * int型の－側オーバーフローを実験する
 *****************************************************************************/
public class Kadai1800{
    public static void main(String[] args){
        int a = -2147483648;                 //int型の最小値を代入
        System.out.println("a     = " + a);  //変数を表示
        a -= 1;                              //最小値からさらに1を減ずる
        System.out.println("a - 1 = " + a);  //どのような値になるか？
    }
}
