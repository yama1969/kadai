/******************************************************************************
 * 文字型の実体は文字コードであることの確認
 *****************************************************************************/
public class Kadai3200{
    public static void main(String[] args){
        char c = 'A';            //文字'A'を代入
        
        System.out.println(c);   //確認のための表示
        
        c += 1;                  //強引に1を加算
        
        System.out.println(c);   //加算後の表示。文字が変わっている
    }
}
