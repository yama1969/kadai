package f_for;

/******************************************************************************
 * 数字を表示
 *****************************************************************************/
public class Kadai1500{
    public static void main(String[] args){
        //7から100まで、7ずつ加算しながら繰り返す
        for(int i = 7; i < 101; i += 7){
            System.out.println(i);
        }
    }
}
