package f_for;

/******************************************************************************
 * 数字を表示
 *****************************************************************************/
public class Kadai1600{
    public static void main(String[] args){
        //98から1まで、7ずつ減じながら繰り返す
        for(int i = 98; i > 0; i -= 7){
            System.out.println(i);
        }
    }
}
