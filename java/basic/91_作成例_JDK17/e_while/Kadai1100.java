package e_while;

/******************************************************************************
 * 数字を表示(1～10昇順)
 *****************************************************************************/
public class Kadai1100{
    public static void main(String[] args){
        int i = 1;                  //初期値 = 1
        while(i < 11){              //1ずつ加算しながら10まで繰り返し
            System.out.println(i);
            i++;
        }
    }
}
