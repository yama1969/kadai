package e_while;

/******************************************************************************
 * 数字を表示(1～100の7の倍数)
 *****************************************************************************/
public class Kadai1500{
    public static void main(String[] args){
        int i = 7;                  //初期値 = 7
        while(i < 101){             //7ずつ加算しながら100を超えない間繰り返す
            System.out.println(i);
            i += 7;
        }
    }
}
