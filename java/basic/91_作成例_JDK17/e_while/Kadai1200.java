package e_while;

/******************************************************************************
 * 数字を表示(62～78昇順)
 *****************************************************************************/
public class Kadai1200{
    public static void main(String[] args){
        int i = 62;                 //初期値=62
        while(i < 79){              //1ずつ加算しながら78まで繰り返す
            System.out.println(i);
            i++;
        }
    }
}
