package e_while;

/******************************************************************************
 * 数字を表示(62～78降順)
 *****************************************************************************/
public class Kadai1400{
    public static void main(String[] args){
        int i = 78;                 //初期値 = 78
        while(i > 61){              //1ずつ減じながら62まで繰り返す
            System.out.println(i);
            i--;
        }
    }
}
