package e_while;

/******************************************************************************
 * 数字を表示(1～100の7の倍数を降順で)
 *****************************************************************************/
public class Kadai1600{
    public static void main(String[] args){
        int i = 98;                //初期値 = 98(100以下の最大の7の倍数)
        while(i > 0){              //7ずつ減じながら1以上の間繰り返す
            System.out.println(i);
            i -= 7;
        }
    }
}
